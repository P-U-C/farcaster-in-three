#!/usr/bin/env bash

set -euo pipefail

IN_THREE_ROOT="${IN_THREE_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
IN_THREE_COMMAND="${IN_THREE_COMMAND:-./farcaster}"
STATE_DIR="${IN_THREE_STATE_DIR:-$IN_THREE_ROOT/.state}"
STATE_FILE="$STATE_DIR/config"
PROOF_DIR="$STATE_DIR/proof"
PROOF_EVENTS_FILE="$PROOF_DIR/events.jsonl"
PROOF_JSON_FILE="$PROOF_DIR/latest.json"
PROOF_REPORT_FILE="$PROOF_DIR/report.md"
SNAPCHAIN_READY_DELAY_SECONDS="${SNAPCHAIN_READY_DELAY_SECONDS:-30}"
SNAPCHAIN_RECOVERY_DELAY_SECONDS="${SNAPCHAIN_RECOVERY_DELAY_SECONDS:-604800}"

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

note() {
  printf '\033[1;35m->\033[0m %s\n' "$*"
}

success() {
  printf '\033[1;32m✓\033[0m %s\n' "$*"
}

snapchain_readiness_json() {
  local info="$1"
  jq -ce \
    --argjson readyThreshold "$SNAPCHAIN_READY_DELAY_SECONDS" \
    --argjson recoveryThreshold "$SNAPCHAIN_RECOVERY_DELAY_SECONDS" '
      (if (.shardInfos? | type) == "array" then .shardInfos else [] end) as $reported
      | [0, 1, 2] as $expected
      | [
          $expected[] as $id
          | ([$reported[]? | select(.shardId == $id)]) as $matches
          | ($matches[0] // {}) as $shard
          | {
              shardId:$id,
              present:(($matches | length) == 1),
              maxHeight:(
                if (($shard.maxHeight? | type) == "number") and $shard.maxHeight >= 0
                then $shard.maxHeight
                else null
                end
              ),
              blockDelay:(
                if (($shard.blockDelay? | type) == "number") and $shard.blockDelay >= 0
                then $shard.blockDelay
                else null
                end
              )
            }
          | . + {
              ready:(.present and (.maxHeight != null) and (.blockDelay != null) and (.blockDelay < $readyThreshold)),
              recoveryRecommended:(.present and (.blockDelay != null) and (.blockDelay >= $recoveryThreshold))
            }
        ] as $shards
      | {
          ready:([$shards[].ready] | all),
          readyThreshold:$readyThreshold,
          recoveryThreshold:$recoveryThreshold,
          missingShards:[$shards[] | select(.present == false) | .shardId],
          recoveryShards:[$shards[] | select(.recoveryRecommended) | .shardId],
          shards:$shards
        }
    ' <<<"$info"
}

snapchain_readiness_lines() {
  local readiness="$1"
  jq -r '
    .shards[]
    | if .present == false then
        "shard \(.shardId)      MISSING"
      elif .blockDelay == null or .maxHeight == null then
        "shard \(.shardId)      INVALID READINESS DATA"
      else
        "shard \(.shardId)      delay \(.blockDelay)s | height \(.maxHeight) | \(if .ready then "READY" elif .recoveryRecommended then "RECOVERY REQUIRED" else "CATCHING UP" end)"
      end
  ' <<<"$readiness"
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "missing required command: $1"
}

utc_now() {
  date -u '+%Y-%m-%dT%H:%M:%SZ'
}

in_three_release() {
  jq -r '.version' "$IN_THREE_ROOT/package.json"
}

record_proof_event() {
  local event="$1"
  local details="${2-}"
  local line
  [[ -n "$details" ]] || details='{}'

  require_command jq
  jq -e 'type == "object"' <<<"$details" >/dev/null ||
    die "proof event details must be a JSON object"
  mkdir -p "$PROOF_DIR"
  chmod 700 "$PROOF_DIR"
  line="$(jq -cn \
    --arg at "$(utc_now)" \
    --arg event "$event" \
    --arg release "$(in_three_release)" \
    --argjson details "$details" \
    '{at:$at,event:$event,release:$release,details:$details}')"
  (umask 077; printf '%s\n' "$line" >> "$PROOF_EVENTS_FILE")
  chmod 600 "$PROOF_EVENTS_FILE"
}

record_proof_event_once() {
  local event="$1"
  local details="${2-}"
  [[ -n "$details" ]] || details='{}'
  if [[ -f "$PROOF_EVENTS_FILE" ]] &&
    jq -e --arg event "$event" 'select(.event == $event)' "$PROOF_EVENTS_FILE" >/dev/null 2>&1; then
    return
  fi
  record_proof_event "$event" "$details"
}

load_state() {
  [[ -f "$STATE_FILE" ]] || die "no provisioned host found; run $IN_THREE_COMMAND provision first"
  # State is generated by our provisioner and is owner-readable only.
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  : "${SERVER_IP:?missing SERVER_IP in state}"
  : "${SSH_KEY:?missing SSH_KEY in state}"
  : "${SSH_USER:=inthree}"
  : "${SSH_PROXY_JUMP:=}"
}

remote() {
  local -a options=(
    -i "$SSH_KEY"
    -o IdentitiesOnly=yes
    -o StrictHostKeyChecking=accept-new
    -o ConnectTimeout=10
  )
  [[ -z "$SSH_PROXY_JUMP" ]] || options+=(-o "ProxyJump=$SSH_PROXY_JUMP")
  # Commands are assembled locally from trusted state and fixed script inputs.
  # shellcheck disable=SC2029
  ssh "${options[@]}" "$SSH_USER@$SERVER_IP" "$@"
}

copy_to() {
  local source="$1"
  local destination="$2"
  local -a options=(
    -i "$SSH_KEY"
    -o IdentitiesOnly=yes
    -o StrictHostKeyChecking=accept-new
    -o ConnectTimeout=10
  )
  [[ -z "$SSH_PROXY_JUMP" ]] || options+=(-o "ProxyJump=$SSH_PROXY_JUMP")
  scp "${options[@]}" "$source" "$SSH_USER@$SERVER_IP:$destination"
}

wait_for_ssh() {
  local attempts="${1:-60}"
  local i
  local -a options=(
    -i "$SSH_KEY"
    -o IdentitiesOnly=yes
    -o StrictHostKeyChecking=accept-new
    -o ConnectTimeout=10
  )
  [[ -z "$SSH_PROXY_JUMP" ]] || options+=(-o "ProxyJump=$SSH_PROXY_JUMP")
  for ((i = 1; i <= attempts; i++)); do
    if ssh "${options[@]}" "$SSH_USER@$SERVER_IP" true >/dev/null 2>&1; then
      return 0
    fi
    if (( i % 6 == 0 )); then
      note "SSH is not ready after $i attempts; still waiting"
    fi
    sleep 5
  done
  return 1
}

hcloud_api() {
  local method="$1"
  local path="$2"
  local data="${3:-}"
  local body_file http_code curl_status response error_code error_message
  body_file="$(mktemp)"
  local -a args=(
    -sS
    --max-time 45
    -o "$body_file"
    -w "%{http_code}"
    -X "$method"
    -H "Authorization: Bearer $HCLOUD_TOKEN"
    -H "Content-Type: application/json"
  )

  [[ -z "$data" ]] || args+=(--data "$data")
  if http_code="$(curl "${args[@]}" "https://api.hetzner.cloud/v1$path")"; then
    curl_status=0
  else
    curl_status=$?
  fi
  response="$(cat "$body_file")"
  rm -f "$body_file"

  if (( curl_status != 0 )); then
    return "$curl_status"
  fi
  if [[ "$http_code" =~ ^2[0-9][0-9]$ ]]; then
    printf '%s' "$response"
    return 0
  fi

  error_code="$(jq -r '.error.code // "http_error"' <<<"$response" 2>/dev/null || printf 'http_error')"
  error_message="$(jq -r '.error.message // "request rejected"' <<<"$response" 2>/dev/null || printf 'request rejected')"
  printf 'error: Hetzner API %s %s failed (HTTP %s, %s): %s\n' \
    "$method" "$path" "$http_code" "$error_code" "$error_message" >&2
  return 1
}

hcloud_delete_with_retry() {
  local path="$1"
  local attempts="${2:-30}"
  local delay_seconds="${3:-2}"
  local attempt
  local http_code="000"

  for ((attempt = 1; attempt <= attempts; attempt++)); do
    if http_code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time 30 -X DELETE \
      -H "Authorization: Bearer $HCLOUD_TOKEN" \
      "https://api.hetzner.cloud/v1$path")"; then
      case "$http_code" in
        200|204|404) return 0 ;;
        409|423|500|502|503|504) ;;
        *)
          printf 'error: delete %s failed with HTTP %s\n' "$path" "$http_code" >&2
          return 1
          ;;
      esac
    fi
    (( attempt == attempts )) || sleep "$delay_seconds"
  done

  printf 'error: delete %s did not complete after %s attempts (last HTTP %s)\n' \
    "$path" "$attempts" "$http_code" >&2
  return 1
}

hcloud_cost_estimate() {
  local server_type_json="$1"
  local pricing_json="$2"
  local location="$3"
  local volume_gib="$4"

  jq -cn \
    --argjson serverTypes "$server_type_json" \
    --argjson pricing "$pricing_json" \
    --arg location "$location" \
    --argjson volumeGiB "$volume_gib" '
      ($serverTypes.server_types[0].prices[] | select(.location == $location)) as $serverPrice
      | ($serverPrice.price_hourly.gross | tonumber) as $serverHourly
      | ($serverPrice.price_monthly.gross | tonumber) as $serverMonthly
      | ($serverMonthly / $serverHourly) as $billingRatio
      | ([
          $pricing.pricing.primary_ips[]?
          | select(.type == "ipv4")
          | .prices[]?
          | select(.location == $location)
        ] | first // {}) as $ipPrice
      | (($ipPrice.price_hourly.gross // "0") | tonumber) as $ipHourly
      | (($ipPrice.price_monthly.gross // "0") | tonumber) as $ipMonthly
      | (($pricing.pricing.volume.price_per_gb_month.gross | tonumber) * $volumeGiB) as $volumeMonthly
      | ($volumeMonthly / $billingRatio) as $volumeHourlyEstimate
      | {
          currency:$pricing.pricing.currency,
          gross:true,
          serverHourly:$serverHourly,
          serverMonthly:$serverMonthly,
          ipv4Hourly:$ipHourly,
          ipv4Monthly:$ipMonthly,
          volumeMonthly:$volumeMonthly,
          volumeHourlyEstimate:$volumeHourlyEstimate,
          totalHourlyEstimate:($serverHourly + $ipHourly + $volumeHourlyEstimate),
          total12Hours:(($serverHourly + $ipHourly + $volumeHourlyEstimate) * 12),
          total24Hours:(($serverHourly + $ipHourly + $volumeHourlyEstimate) * 24),
          totalMonthly:($serverMonthly + $ipMonthly + $volumeMonthly)
        }
    '
}

sha256_file() {
  local path="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$path" | awk '{print $1}'
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$path" | awk '{print $1}'
  else
    die "missing SHA-256 tool: install sha256sum or shasum"
  fi
}

secure_delete() {
  local path="$1"
  [[ -e "$path" ]] || return 0
  if command -v shred >/dev/null 2>&1; then
    shred -u "$path" 2>/dev/null || rm -f "$path"
  else
    rm -f "$path"
  fi
}
